import {
  Route,
  Star,
  Clock,
  Users as UsersIcon,
  ArrowRight,
  CheckCircle2,
  PlayCircle,
  Circle,
  GraduationCap,
  Sparkles,
  TrendingUp,
  X,
  ExternalLink,
  Info,
} from 'lucide-react';
import { Card, Badge, ProgressBar, PageHeader, Button } from '@/components/ui';
import { learningPath } from '@/data/mockData';
import { useApp } from '@/context/AppContext';
import { openIGOTCourse, IGOT_COURSE_LIST_URL } from '@/utils/igotUtils';
import { cn } from '@/utils/cn';
import type { Course } from '@/types';
import { useState } from 'react';

export function LearningPathPage() {
  const { isEnrolled, enrollCourse, getOfficerRecommendations, userScores } = useApp();
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  const recommendations = getOfficerRecommendations(userScores);

  const handleEnroll = (courseId: string) => {
    enrollCourse(courseId);
  };

  const handleOpenIGOT = (course: Course) => {
    openIGOTCourse(course.igotUrl || IGOT_COURSE_LIST_URL, (msg) => {
      setToastMessage(msg);
      setTimeout(() => setToastMessage(null), 3000);
    });
  };

  return (
    <>
      <PageHeader
        title="Personalized Learning Path & Recommendations"
        subtitle="AI-recommended iGOT courses generated by the NLP Semantic Matching layer"
      >
        <Badge variant="primary" className="bg-primary-50 text-primary-700 border-primary-200">
          <Sparkles size={12} /> NLP Semantic Engine
        </Badge>
      </PageHeader>

      {/* Prototype note banner */}
      <div className="mb-6 p-4 rounded-xl bg-neutral-100/90 border border-neutral-200 flex items-start gap-3 text-xs text-neutral-600">
        <Info size={18} className="text-primary-600 shrink-0 mt-0.5" />
        <div className="flex-1">
          <p className="font-bold text-neutral-800">
            Verified/Curated iGOT Course Dataset + NLP Semantic Matching
          </p>
          <p className="mt-0.5 text-neutral-600">
            The platform compares identified competency gaps with curated course syllabi, titles, and competency tags to determine semantic relevance.
          </p>
          <p className="italic text-neutral-500 mt-1">
            "Prototype uses a curated course dataset to demonstrate iGOT course mapping. Live API integration can be added when official API access is available."
          </p>
        </div>
      </div>

      {/* Current path timeline */}
      <Card className="p-6 mb-6">
        <h3 className="text-sm font-semibold text-neutral-900 mb-1">Active Learning Path Timeline</h3>
        <p className="text-xs text-neutral-500 mb-6">Sequenced courses to close competency gaps progressively</p>
        <div className="relative">
          {/* Timeline line */}
          <div className="absolute left-4 top-0 bottom-0 w-0.5 bg-neutral-200" />
          <div className="space-y-4">
            {learningPath.map((item) => (
              <div key={item.courseId} className="flex items-start gap-4 relative">
                <div
                  className={cn(
                    'flex items-center justify-center w-8 h-8 rounded-full border-2 bg-white shrink-0 z-10',
                    item.status === 'completed'
                      ? 'border-success-500 bg-success-500 text-white'
                      : item.status === 'in_progress'
                        ? 'border-primary-500 bg-primary-50 text-primary-600'
                        : 'border-neutral-300 bg-white text-neutral-400'
                  )}
                >
                  {item.status === 'completed' ? (
                    <CheckCircle2 size={16} />
                  ) : item.status === 'in_progress' ? (
                    <PlayCircle size={16} />
                  ) : (
                    <Circle size={16} />
                  )}
                </div>
                <div className="flex-1 min-w-0">
                  <div className="flex items-center gap-2 mb-1">
                    <p className="text-sm font-medium text-neutral-800">{item.courseTitle}</p>
                    <Badge variant={item.source === 'igot' ? 'secondary' : 'default'}>
                      {item.source === 'igot' ? 'iGOT' : 'Internal'}
                    </Badge>
                  </div>
                  <ProgressBar
                    value={item.progress}
                    variant={item.status === 'completed' ? 'success' : 'primary'}
                    showLabel
                    className="max-w-xs"
                  />
                  <p className="text-xs text-neutral-500 mt-1 capitalize">
                    {item.status.replace('_', ' ')}
                  </p>
                </div>
              </div>
            ))}
          </div>
        </div>
      </Card>

      {/* Recommendations */}
      <div className="mb-4">
        <h3 className="text-sm font-semibold text-neutral-900 mb-1">Personalized Course Recommendations</h3>
        <p className="text-xs text-neutral-500">
          Ranked by NLP semantic match score — addresses gap severity, domain terminology, and officer learner context
        </p>
      </div>

      <div className="space-y-4">
        {recommendations.map((rec) => {
          const course = rec.course;
          const enrolled = isEnrolled(course.id);

          return (
            <Card key={course.id} className="p-5" hover>
              <div className="flex flex-col lg:flex-row gap-4">
                {/* Priority & Match score badge */}
                <div className="flex lg:flex-col items-center gap-2 lg:gap-1 shrink-0">
                  <div
                    className={cn(
                      'flex items-center justify-center w-10 h-10 rounded-xl font-bold text-sm shadow-xs',
                      rec.priority <= 2
                        ? 'bg-error-100 text-error-700'
                        : rec.priority <= 4
                          ? 'bg-warning-100 text-warning-700'
                          : 'bg-neutral-100 text-neutral-600'
                    )}
                  >
                    #{rec.priority}
                  </div>
                  <div className="text-center">
                    <p className="text-[10px] uppercase font-bold text-neutral-400">Match</p>
                    <p className="text-sm font-extrabold text-emerald-600">{rec.matchScore}%</p>
                  </div>
                </div>

                {/* Course info */}
                <div className="flex-1 min-w-0">
                  <div className="flex items-start justify-between gap-2 mb-2">
                    <div className="min-w-0">
                      <div className="flex items-center gap-2 mb-1 flex-wrap">
                        <span className="font-mono text-[10px] font-bold text-neutral-500 bg-neutral-100 px-1.5 py-0.2 rounded">
                          Course ID: {course.id}
                        </span>
                        <h4 className="text-base font-bold text-neutral-900 truncate">{course.title}</h4>
                        <Badge variant={course.source === 'igot' ? 'secondary' : 'default'}>
                          {course.source === 'igot' ? (
                            <>
                              <GraduationCap size={10} /> iGOT
                            </>
                          ) : (
                            'Internal'
                          )}
                        </Badge>
                      </div>

                      <p className="text-xs font-bold text-primary-700 mb-1">
                        Relevant Skill: <span className="text-neutral-800">{rec.relevantSkill || 'Data Analysis'}</span>
                      </p>

                      <p className="text-xs text-neutral-600 line-clamp-2 leading-relaxed">{course.description}</p>
                    </div>
                  </div>

                  {/* Meta info */}
                  <div className="flex flex-wrap items-center gap-4 mt-2 text-xs text-neutral-500">
                    <span className="flex items-center gap-1">
                      <Clock size={12} /> {course.duration}
                    </span>
                    <span className="flex items-center gap-1">
                      <Star size={12} className="text-accent-500" /> {course.rating} ({course.ratingCount})
                    </span>
                    <span className="flex items-center gap-1">
                      <UsersIcon size={12} /> {course.enrolled.toLocaleString('en-IN')} enrolled
                    </span>
                    <Badge
                      variant={
                        course.difficulty === 'easy'
                          ? 'success'
                          : course.difficulty === 'medium'
                            ? 'warning'
                            : 'error'
                      }
                      className="capitalize"
                    >
                      {course.difficulty}
                    </Badge>
                  </div>

                  {/* Reason & Gap Addressed */}
                  <div className="mt-3 p-3 rounded-lg bg-primary-50 border border-primary-100 text-xs">
                    <p className="text-neutral-700 leading-relaxed">
                      <span className="font-bold text-primary-800">NLP Matching Rationale: </span>
                      {rec.reason}
                    </p>
                    <div className="flex items-center gap-4 mt-2 text-xs flex-wrap">
                      <span className="text-neutral-600">
                        <span className="font-semibold">Gap addressed:</span> {rec.gapAddressed}
                      </span>
                      <span className="flex items-center gap-1 text-success-700 font-bold">
                        <TrendingUp size={12} /> Est. +{rec.estimatedImprovement}% competency improvement
                      </span>
                    </div>
                  </div>

                  {/* Topics */}
                  <div className="flex flex-wrap gap-1.5 mt-3">
                    {course.topics.map((topic) => (
                      <span
                        key={topic}
                        className="px-2 py-0.5 rounded text-[10px] font-medium bg-neutral-100 text-neutral-600"
                      >
                        {topic}
                      </span>
                    ))}
                  </div>
                </div>

                {/* Action buttons */}
                <div className="flex lg:flex-col gap-2 shrink-0 justify-center">
                  {!enrolled ? (
                    <Button
                      size="sm"
                      className="flex-1 lg:w-full"
                      onClick={() => handleEnroll(course.id)}
                    >
                      Enroll <ArrowRight size={14} />
                    </Button>
                  ) : (
                    <Button
                      size="sm"
                      variant="outline"
                      className="flex-1 lg:w-full border-success-300 text-success-700"
                    >
                      <CheckCircle2 size={14} className="text-success-600" />
                      Enrolled
                    </Button>
                  )}
                  <Button
                    variant="primary"
                    size="sm"
                    className="flex-1 lg:w-full flex items-center justify-center gap-1.5 font-bold"
                    onClick={() => handleOpenIGOT(course)}
                    title={`Open course list on iGOT: ${course.title}`}
                  >
                    <ExternalLink size={13} /> View Course
                  </Button>
                </div>
              </div>
            </Card>
          );
        })}
      </div>

      {/* Alternative options info */}
      <Card className="p-5 mt-6 bg-neutral-50 border-neutral-200">
        <div className="flex items-start gap-3">
          <X size={18} className="text-neutral-400 shrink-0 mt-0.5" />
          <div>
            <p className="text-sm font-semibold text-neutral-700">Alternative Learning Options</p>
            <p className="text-xs text-neutral-500 mt-1">
              If you decline an iGOT course, the platform will suggest internal courses or
              uploaded learning materials that address the same competency gap. You can also
              upload your own study materials and generate AI quizzes for self-paced learning.
            </p>
          </div>
        </div>
      </Card>

      {/* Toast notification */}
      {toastMessage && (
        <div className="fixed bottom-6 left-1/2 -translate-x-1/2 z-50 flex items-center gap-2 bg-neutral-900 text-white text-sm font-medium px-5 py-3 rounded-full shadow-xl animate-fade-in">
          <CheckCircle2 size={16} className="text-amber-400" />
          {toastMessage}
        </div>
      )}
    </>
  );
}
